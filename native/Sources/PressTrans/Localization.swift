    static var systemLanguage:String {
        let code=Locale.preferredLanguages.first ?? "en"
        if code.hasPrefix("zh") {return code.contains("Hant") || code.contains("TW") || code.contains("HK") ? "Chinese (Traditional)":"Chinese (Simplified)"}

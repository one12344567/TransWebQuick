func L(_ text:String)->String {
    let normalized=text.applyingTransform(StringTransform("Hant-Hans"),reverse:false) ?? text
    let key=AppLanguage.english[normalized] == nil ? (AppLanguage.english.first(where:{$0.value == text})?.key ?? text):normalized
    switch AppLanguage.current {
    case "zh-Hans":return key
    case "zh-Hant":return key.applyingTransform(StringTransform("Hans-Hant"),reverse:false) ?? key
    default:return AppLanguage.english[key] ?? text
    }
}
